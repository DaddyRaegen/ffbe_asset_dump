def port_events(original: bytes) -> bytes:
    """Return the pinned reference event behavior from pinned Patch5 bytes."""
    if hashlib.sha256(original).hexdigest() != PATCH5_SCRIPT_SHA256:
        raise ValueError('Production Patch5 Frida script hash mismatch')
    text = original.decode('utf-8')
    if text.count(PARTY_MARKER) != 1:
        raise ValueError('Patch5 party-map marker is not unique')
    start = text.index(PARTY_MARKER) + len(PARTY_MARKER)
    parties, length = json.JSONDecoder().raw_decode(text[start:])
    if set(parties) != {'books', 'entries'} or len(parties['books']) != 85 or len(parties['entries']) != 2177:
        raise ValueError('Patch5 party-map baseline counts mismatch')
    for book in ADDED_IMPORTED_BOOK_IDS:
        key = str(book)
        if key in parties['books']:
            raise ValueError('Imported-book port would overwrite a baseline party')
        parties['books'][key] = []
    if len(parties['books']) != 916 or len(ADDED_IMPORTED_BOOK_IDS) != 831:
        raise ValueError('Imported-book event port counts mismatch')
    text = text[:start] + json.dumps(parties, separators=(',', ':'), ensure_ascii=False) + text[start + length:]
    if text.count(OLD_IMPORTED_CLASSIFIER) != 1 or text.count('const PATCH_VERSION = 5;') != 1:
        raise ValueError('Patch5 event-classifier/version markers mismatch')
    text = text.replace(OLD_IMPORTED_CLASSIFIER, NEW_IMPORTED_CLASSIFIER)
    text = text.replace('const PATCH_VERSION = 5;', 'const PATCH_VERSION = 6;')
    # Reproduce the frozen reference's historical CRLF expansion solely so the
    # complete event port can be verified against the immutable v201 byte pin.
    output = text.replace('\r\n', '\n\n').replace('\n', '\r\n').encode('utf-8')
    if hashlib.sha256(output).hexdigest() != FROZEN201_SCRIPT_SHA256:
        raise ValueError('Event port did not reproduce the reviewed reference')
    return output
